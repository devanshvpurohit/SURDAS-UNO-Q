"""
HAL Sensor Providers for SURDAS on Arduino UNO Q.
Provides hardware-independent IMU / Fall detection abstraction,
distinguishing real hardware telemetry from simulation.
"""

import abc
import time
import math
import random
import logging
from dataclasses import dataclass, asdict
from typing import Optional, Dict, Any

logger = logging.getLogger("surdas.hal.sensor")


@dataclass
class IMUReading:
    """Standardized IMU & Fall Detection data structure."""
    ax: float
    ay: float
    az: float
    acceleration: float
    pitch: float
    roll: float
    falls: int
    state: str           # "NORMAL", "TILT_WARNING", "FREEFALL", "IMPACT", "FALL_CONFIRMED"
    source: str          # "HARDWARE" or "SIMULATION"
    timestamp: float
    mpu: str = "STM32_IMU"

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


class IMUProvider(abc.ABC):
    """Abstract interface for IMU and motion sensor providers."""

    @abc.abstractmethod
    def get_reading(self) -> Optional[IMUReading]:
        """Return the latest IMU reading, or None if unavailable."""
        pass

    @abc.abstractmethod
    def is_connected(self) -> bool:
        """Return True if real physical sensor hardware is actively streaming."""
        pass

    @abc.abstractmethod
    def is_simulated(self) -> bool:
        """Return True if data is generated by simulation."""
        pass

    @abc.abstractmethod
    def trigger_simulated_fall(self) -> None:
        """Trigger a simulated fall sequence for testing/demonstration."""
        pass

    @abc.abstractmethod
    def reset_falls(self) -> None:
        """Reset the fall counter."""
        pass


class BridgeIMUProvider(IMUProvider):
    """
    Reads IMU telemetry received from the Arduino UNO Q STM32 microcontroller
    via the Bridge RPC or serial connection.
    """

    def __init__(self, bridge_client: Any = None):
        self.bridge = bridge_client
        self.last_reading: Optional[IMUReading] = None
        self.last_update_time = 0.0
        self.fall_count = 0

    def update_from_bridge_data(self, data: Dict[str, Any]) -> None:
        """Called when a telemetry packet arrives from STM32."""
        now = time.time()
        self.last_update_time = now
        ax = float(data.get("ax", 0.0))
        ay = float(data.get("ay", 0.0))
        az = float(data.get("az", 1.0))
        acc = float(data.get("acceleration", math.sqrt(ax*ax + ay*ay + az*az)))
        pitch = float(data.get("pitch", 0.0))
        roll = float(data.get("roll", 0.0))
        state = str(data.get("state", "NORMAL"))
        if state == "FALL_CONFIRMED":
            self.fall_count += 1

        self.last_reading = IMUReading(
            ax=round(ax, 3),
            ay=round(ay, 3),
            az=round(az, 3),
            acceleration=round(acc, 3),
            pitch=round(pitch, 1),
            roll=round(roll, 1),
            falls=int(data.get("falls", self.fall_count)),
            state=state,
            source="HARDWARE",
            timestamp=now,
            mpu="STM32U585_IMU"
        )

    def get_reading(self) -> Optional[IMUReading]:
        # Stale if no packet for > 3.0 seconds
        if self.last_reading and (time.time() - self.last_update_time < 3.0):
            return self.last_reading
        return None

    def is_connected(self) -> bool:
        return self.last_reading is not None and (time.time() - self.last_update_time < 3.0)

    def is_simulated(self) -> bool:
        return False

    def trigger_simulated_fall(self) -> None:
        # Physical provider does not simulate
        pass

    def reset_falls(self) -> None:
        self.fall_count = 0


class SimulatedIMUProvider(IMUProvider):
    """
    Deterministic simulated IMU provider for development and testing.
    Explicitly tags all readings with source='SIMULATION' so the UI can badge it.
    """

    def __init__(self):
        self.fall_count = 0
        self.sim_fall_phase = 0  # 0: normal, 1: freefall, 2: impact, 3: resting on floor
        self.sim_fall_start = 0.0

    def get_reading(self) -> IMUReading:
        now = time.time()

        # Handle active simulated fall sequence
        if self.sim_fall_phase > 0:
            elapsed = now - self.sim_fall_start
            if elapsed < 0.3:
                # Phase 1: Freefall (near 0g)
                return IMUReading(
                    ax=0.05, ay=0.08, az=0.15, acceleration=0.18,
                    pitch=25.0, roll=10.0, falls=self.fall_count,
                    state="FREEFALL", source="SIMULATION", timestamp=now
                )
            elif elapsed < 0.8:
                # Phase 2: Impact spike (>2.5g)
                return IMUReading(
                    ax=1.8, ay=2.1, az=1.4, acceleration=3.1,
                    pitch=75.0, roll=-40.0, falls=self.fall_count,
                    state="IMPACT", source="SIMULATION", timestamp=now
                )
            elif elapsed < 4.0:
                # Phase 3: Fallen position (prolonged lie-down tilt >60 deg)
                return IMUReading(
                    ax=0.1, ay=0.95, az=0.12, acceleration=0.98,
                    pitch=82.0, roll=-45.0, falls=self.fall_count,
                    state="FALL_CONFIRMED", source="SIMULATION", timestamp=now
                )
            else:
                # Return to normal
                self.sim_fall_phase = 0

        # Normal standing / slight sway dynamics
        t = now * 1.5
        noise = random.uniform(-0.02, 0.02)
        ax = 0.05 * math.sin(t) + noise
        ay = 0.03 * math.cos(t * 1.3) + noise
        az = 0.98 + 0.02 * math.sin(t * 0.7)
        acc = math.sqrt(ax*ax + ay*ay + az*az)
        pitch = 3.0 * math.sin(t)
        roll = 2.0 * math.cos(t)

        return IMUReading(
            ax=round(ax, 3),
            ay=round(ay, 3),
            az=round(az, 3),
            acceleration=round(acc, 3),
            pitch=round(pitch, 1),
            roll=round(roll, 1),
            falls=self.fall_count,
            state="NORMAL",
            source="SIMULATION",
            timestamp=now
        )

    def is_connected(self) -> bool:
        return False  # Real hardware is NOT connected

    def is_simulated(self) -> bool:
        return True

    def trigger_simulated_fall(self) -> None:
        self.fall_count += 1
        self.sim_fall_phase = 1
        self.sim_fall_start = time.time()
        logger.info(f"Triggered simulated fall event (Total: {self.fall_count})")

    def reset_falls(self) -> None:
        self.fall_count = 0
        self.sim_fall_phase = 0


def create_imu_provider(enable_simulation: bool = True) -> IMUProvider:
    """
    Factory creating IMU provider. If real bridge is unavailable,
    uses SimulatedIMUProvider (if enabled) with visible SIMULATION tag.
    """
    # In future or on actual UNO Q hardware, probe BridgeIMUProvider first
    if enable_simulation:
        return SimulatedIMUProvider()
    return BridgeIMUProvider()
